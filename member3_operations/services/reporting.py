from io import BytesIO
from xml.sax.saxutils import escape

from django.core.files.base import ContentFile
from django.utils import timezone
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from member2_assessment.models import VulnerabilityFinding
from ..models import Report

SEVERITY_RANK = {"critical": 0, "high": 1, "medium": 2, "low": 3, "info": 4}


def generate_report(scan, user):
    findings = list(VulnerabilityFinding.objects.filter(scan_id=scan.id)
                    .select_related("host").prefetch_related("evidences", "remediation"))
    findings.sort(key=lambda f: SEVERITY_RANK.get(f.severity, 9))
    buffer = BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, leftMargin=18*mm, rightMargin=18*mm,
                            topMargin=18*mm, bottomMargin=18*mm)
    styles = getSampleStyleSheet()
    h1 = ParagraphStyle("H1", parent=styles["Heading1"], fontSize=18)
    h2 = ParagraphStyle("H2", parent=styles["Heading2"], fontSize=13)
    body = styles["BodyText"]
    code = ParagraphStyle("Code", parent=styles["Code"], fontSize=7, leading=9)

    story = [
        Paragraph("VulnTrack Security Assessment Report", h1),
        Paragraph(f"Scan #{scan.id} — {escape(scan.target.name)}", h2),
        Spacer(1, 6),
    ]
    meta = [["Generated by", user.get_username()],
            ["Generated at", timezone.now().strftime("%Y-%m-%d %H:%M UTC")],
            ["Scan status", scan.get_status_display()]]
    t = Table(meta)
    t.setStyle(TableStyle([("GRID", (0,0), (-1,-1), 0.4, colors.grey)]))
    story.append(t)
    story.append(Spacer(1, 10))

    for i, f in enumerate(findings, 1):
        story.append(Paragraph(f"{i}. {escape(f.title)}", h2))
        story.append(Paragraph(
            f"<b>Severity:</b> {f.get_severity_display()} &nbsp; "
            f"<b>Host:</b> {escape(f.host.hostname) if f.host else '-'}", body))
        story.append(Paragraph(escape(f.description or ""), body))
        for ev in f.evidences.all():
            story.append(Paragraph(f"<b>Request:</b><br/>{escape(ev.request_data[:800]).replace(chr(10), '<br/>')}", code))
            story.append(Paragraph(f"<b>Response:</b><br/>{escape(ev.response_data[:800]).replace(chr(10), '<br/>')}", code))
        rem = getattr(f, "remediation", None)
        if rem:
            story.append(Paragraph(f"<b>Remediation:</b> {escape(rem.recommendation)}", body))
        story.append(Spacer(1, 8))

    if not findings:
        story.append(Paragraph("No findings recorded.", body))
    doc.build(story)
    report = Report(scan=scan, generated_by=user, title=f"Security Report — Scan #{scan.id}")
    filename = f"scan_{scan.id}_{timezone.now():%Y%m%d%H%M%S}.pdf"
    report.file.save(filename, ContentFile(buffer.getvalue()), save=True)
    return report
